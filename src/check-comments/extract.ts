import { type PatchHunk, type PatchLine, parseCommentDiff } from "./diff.js";
import { CommentLexer, commentLanguage } from "./lexer.js";

const MAX_COMMENT_BYTES = 8 * 1024;
const MAX_CONTEXT_LINE_BYTES = 256;
const MAX_DIFF_COMMENTS = 10_000;
const MAX_HUNK_PARTS = 20_000;
const CONTEXT_RADIUS = 2;
const CONTEXT_MAX_LINES = 12;
const GENERATED_PATH =
  /(?:^|\/)(?:__generated__|generated|node_modules|vendor)(?:\/|$)|\.(?:min|generated|gen|pb|g)\.[^/]+$|(?:^|\/)zz_generated[^/]*$/i;
const LOCK_PATH =
  /(?:^|\/)(?:[^/]+\.lock(?:\.json)?|package-lock\.json|npm-shrinkwrap\.json|go\.sum|pnpm-lock\.ya?ml|bun\.lockb)$/i;
const GENERATED_HEADER =
  /^(?:@generated\b|(?:automatically generated|auto-generated|autogenerated)\b|code generated\b.*\bdo not edit\b|this file (?:is|was) (?:automatically )?generated\b)/i;
const LICENSE_HEADER =
  /^(?:SPDX-(?:License-Identifier|FileCopyrightText):|Copyright(?:\s|\(c\)|©)|Licensed under\b|Permission is hereby granted\b|This (?:source code|file) is licensed\b|All rights reserved\b)/i;
const DIRECTIVE =
  /^(?:!\/|eslint-(?:disable|enable)\b|(?:eslint-env|global|globals|prettier-ignore(?:-start|-end)?|biome-ignore(?:-all|-start|-end)?|oxlint-(?:disable|enable)|deno-lint-ignore(?:-file)?|tslint:(?:disable|enable)|type:\s*ignore|ruff:\s*noqa|pylint:\s*(?:disable|enable)|pyright:\s*ignore|isort:\s*skip|fmt:\s*(?:off|on|skip)|sqlfluff:\s*disable|nosemgrep|shellcheck\s|stylua:\s*ignore|lua-language-server)\b|@(?:ts-(?:ignore|expect-error|nocheck|check)|vite-ignore|__PURE__)\b|#?__PURE__\b|#?__NO_SIDE_EFFECTS__\b|nolint\b|noqa\b|noinspection\b|swiftlint:(?:disable|enable)\b|(?:go:(?:build|generate|embed|linkname|noinline|nosplit|nocheckptr|noescape)|line\s+\S+:\d+|\+\s*build)\b)/i;

export interface DiffComment {
  readonly path: string;
  readonly startLine: number;
  readonly endLine: number;
  readonly text: string;
  readonly context: string;
  readonly oversized?: true;
}

interface LocatedPart {
  readonly text: string;
  readonly number: number;
  readonly standalone: boolean;
  readonly blockId?: number;
}

interface CommentGroup {
  readonly parts: LocatedPart[];
  readonly blockId?: number;
  readonly standalone: boolean;
}

function commentContent(text: string): string {
  return text.replace(/^(?:\/\/+|#+|--(?:\[=*\[)?|\/\*+|<!--|\*)\s*/, "");
}

function clippedLine(text: string): string {
  const bytes = Buffer.from(text.slice(0, MAX_CONTEXT_LINE_BYTES));
  if (text.length <= MAX_CONTEXT_LINE_BYTES && bytes.length <= MAX_CONTEXT_LINE_BYTES) return text;
  return `${bytes.subarray(0, MAX_CONTEXT_LINE_BYTES - 3).toString("utf8")}…`;
}

function commentContext(lines: readonly PatchLine[], first: number, last: number): string {
  const start = Math.max(0, first - CONTEXT_RADIUS);
  const end = Math.min(lines.length, last + CONTEXT_RADIUS + 1);
  const indices =
    end - start <= CONTEXT_MAX_LINES
      ? Array.from({ length: end - start }, (_, index) => start + index)
      : [
          ...Array.from({ length: CONTEXT_MAX_LINES / 2 }, (_, index) => start + index),
          -1,
          ...Array.from(
            { length: CONTEXT_MAX_LINES / 2 },
            (_, index) => end - CONTEXT_MAX_LINES / 2 + index,
          ),
        ];
  return indices
    .map((index) => {
      const line = lines[index];
      return line === undefined ? "[…]" : line.kind + clippedLine(line.text);
    })
    .join("\n");
}

function addPart(
  groups: CommentGroup[],
  blocks: Map<number, CommentGroup>,
  part: LocatedPart,
): void {
  if (part.blockId !== undefined) {
    const group = blocks.get(part.blockId);
    if (group !== undefined) {
      group.parts.push(part);
      return;
    }
    const created = { parts: [part], blockId: part.blockId, standalone: part.standalone };
    blocks.set(part.blockId, created);
    groups.push(created);
    return;
  }
  const last = groups.at(-1);
  if (
    part.standalone &&
    last?.standalone &&
    last.blockId === undefined &&
    last.parts.at(-1)?.number === part.number - 1
  ) {
    last.parts.push(part);
  } else {
    groups.push({ parts: [part], standalone: part.standalone });
  }
}

interface HunkComments {
  readonly groups: readonly CommentGroup[];
  readonly licenseBlockIds: ReadonlySet<number>;
  readonly generated: boolean;
}

function extractHunk(
  hunk: PatchHunk,
  newLines: readonly PatchLine[],
  newLexer: CommentLexer,
  oldLexer: CommentLexer,
): HunkComments {
  const parts: { readonly part: LocatedPart; readonly signature: string }[] = [];
  const removed = new Map<string, number>();
  const licenseBlockIds = new Set<number>();
  let generated = false;
  let section = 0;
  let fragments = 0;
  const oldLines = hunk.lines.filter((line) => line.kind !== "+");
  let nextOldIndex = 1;
  function countFragments(count: number): void {
    fragments += count;
    if (fragments > MAX_HUNK_PARTS) {
      throw new Error("[COMMENT_DIFF_LIMIT] A diff hunk contains too many comment fragments.");
    }
  }
  for (const line of hunk.lines) {
    if (line.kind === " ") section += 1;
    if (line.kind !== "+") {
      const oldParts = oldLexer.scan(line.text, oldLines[nextOldIndex]?.text);
      nextOldIndex += 1;
      if (line.kind === "-") {
        countFragments(oldParts.length);
        for (const piece of oldParts) {
          const signature = `${section}:${line.text.slice(piece.start, piece.end).trim()}`;
          removed.set(signature, (removed.get(signature) ?? 0) + 1);
        }
      }
    }
    if (line.kind === "-") continue;
    const newParts = newLexer.scan(line.text, newLines[line.number - hunk.firstNewLine + 1]?.text);
    countFragments(newParts.length);
    for (const piece of newParts) {
      const text = line.text.slice(piece.start, piece.end).trim();
      if (!text) continue;
      const content = commentContent(text);
      if (line.number <= 20 && GENERATED_HEADER.test(content)) generated = true;
      if (line.number <= 35 && piece.blockId !== undefined && LICENSE_HEADER.test(content)) {
        licenseBlockIds.add(piece.blockId);
      }
      if (
        line.kind !== "+" ||
        DIRECTIVE.test(content) ||
        (piece.blockId === undefined && line.number <= 35 && LICENSE_HEADER.test(content))
      )
        continue;
      parts.push({
        signature: `${section}:${text}`,
        part: {
          text,
          number: line.number,
          standalone: piece.standalone,
          ...(piece.blockId === undefined ? {} : { blockId: piece.blockId }),
        },
      });
    }
  }
  const groups: CommentGroup[] = [];
  const blocks = new Map<number, CommentGroup>();
  for (const { part, signature } of parts) {
    const count = removed.get(signature) ?? 0;
    if (count > 0) removed.set(signature, count - 1);
    else addPart(groups, blocks, part);
  }
  return { groups, licenseBlockIds, generated };
}

function fileComments(
  path: string,
  hunks: readonly PatchHunk[],
  language: NonNullable<ReturnType<typeof commentLanguage>>,
): DiffComment[] {
  const comments: DiffComment[] = [];
  let oldLexer = new CommentLexer(language);
  let newLexer = new CommentLexer(language);
  let nextOld = 1;
  let nextNew = 1;
  for (const hunk of hunks) {
    if (hunk.firstOldLine !== nextOld) oldLexer = new CommentLexer(language);
    if (hunk.firstNewLine !== nextNew) newLexer = new CommentLexer(language);
    nextOld = hunk.firstOldLine + hunk.oldLines;
    nextNew = hunk.firstNewLine + hunk.newLines;
    const newLines = hunk.lines.filter((line) => line.kind !== "-");
    const result = extractHunk(hunk, newLines, newLexer, oldLexer);
    if (result.generated) return [];
    for (const group of result.groups) {
      const first = group.parts[0];
      const last = group.parts.at(-1);
      if (first === undefined || last === undefined) continue;
      if (group.blockId !== undefined && result.licenseBlockIds.has(group.blockId)) continue;
      if (first.number <= 35 && LICENSE_HEADER.test(commentContent(first.text))) continue;
      const text = group.parts.map((part) => part.text).join("\n");
      // A delimiter-only addition cannot itself communicate an excuse, edge-case dismissal or TODO.
      if (!group.parts.some((part) => /[\p{L}\p{N}]/u.test(commentContent(part.text)))) continue;
      const oversized = Buffer.byteLength(text, "utf8") > MAX_COMMENT_BYTES;
      comments.push({
        path,
        startLine: first.number,
        endLine: last.number,
        text: oversized ? "" : text,
        context: oversized
          ? ""
          : commentContext(
              newLines,
              first.number - hunk.firstNewLine,
              last.number - hunk.firstNewLine,
            ),
        ...(oversized ? { oversized: true } : {}),
      });
      if (comments.length > MAX_DIFF_COMMENTS) tooManyComments();
    }
  }
  return comments;
}

function tooManyComments(): never {
  throw new Error("[COMMENT_DIFF_LIMIT] Unified diff exceeds 10,000 comment blocks.");
}

export function extractDiffComments(diff: string): DiffComment[] {
  const comments: DiffComment[] = [];
  for (const { path, hunks } of parseCommentDiff(diff)) {
    if (path === null || GENERATED_PATH.test(path) || LOCK_PATH.test(path)) continue;
    const language = commentLanguage(path);
    if (language === undefined) continue;
    const fromFile = fileComments(path, hunks, language);
    if (comments.length + fromFile.length > MAX_DIFF_COMMENTS) tooManyComments();
    for (const comment of fromFile) comments.push(comment);
  }
  return comments;
}
